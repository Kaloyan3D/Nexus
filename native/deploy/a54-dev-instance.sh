#!/bin/sh
# A5.4 isolated dev instance for the OpenCode Go live acceptance.
# Single-UID development pilot (shadow-test trust, model-only scope). It never
# touches production-v1 or the legacy DSH Registry: everything lives under
# $A54_HOME (default ~/.nexus-a54, mode 0700).
#
#   sh deploy/a54-dev-instance.sh prepare     create dirs, Registry records (offline)
#   sh deploy/a54-dev-instance.sh credentials write credentials.json from the existing OPENCODE_API_KEY (env, then repo .env; parsed, never printed)
#   sh deploy/a54-dev-instance.sh start       start nexusd + nexus-broker (no network egress by itself)
#   sh deploy/a54-dev-instance.sh synthetic-repo   create $A54_HOME/inspect-repo (synthetic sources, no secrets) for A5.5
#   (A5.5) export A55_WORKSPACE=ID=ABS_PATH before `start` to enable read-only repo-inspect on that ONE workspace
#   sh deploy/a54-dev-instance.sh synthetic-code-repo   create $A54_HOME/code-base/repo (a tiny Rust crate with a FAILING test, committed) for A5.6
#   (A5.6) export A56_CODE_SOURCE=ID=ABS_PATH before `start` to enable repo-code on that ONE git repository (single-UID,
#          TEST-ONLY approver: a human must still approve every edit/command with the approver tool; see docs/A5.6-LIVE-ACCEPTANCE.md)
#   (A6.1.3) export A613_PROJECT_REGISTRY=/abs/dir instead for several registered projects (see docs/A6.1.3-PROJECT-OPERATIONS.md)
#   (A6.1) also set A56_CODE_COMMIT=<40-hex> to pin the source to one commit and A61_CODE_WRITE_ALLOW=dir/,file to scope model writes, A61_DEP_CACHE=/abs/dir for dependency-bearing builds
#   sh deploy/a54-dev-instance.sh check      read-only: is the running broker the installed build?
#   sh deploy/a54-dev-instance.sh stop
#   sh deploy/a54-dev-instance.sh env         print the exports for the CLI
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
REPO=$(cd "$HERE/../.." && pwd)
BIN=${BIN_DIR:-$REPO/native/target/debug}
A=${A54_HOME:-$HOME/.nexus-a54}
case "$A" in *production*|*/.nexus|*/.nexus/) echo "refusing to use a production-looking home: $A" >&2; exit 2;; esac
cmd=${1:-}
umask 077
case "$cmd" in
prepare)
  mkdir -p "$A/registry" "$A/daemon" "$A/broker" "$A/transcripts"
  chmod 700 "$A" "$A/registry" "$A/daemon" "$A/broker" "$A/transcripts"
  node "$REPO/scripts/Setup-NativeOpenCodeGo.cjs" --data-root "$A/registry" --apply
  echo "next: sh deploy/a54-dev-instance.sh credentials   (see native/docs/A5.4-LIVE-ACCEPTANCE.md)"
  ;;
credentials)
  mkdir -p "$A" && chmod 700 "$A"
  node "$REPO/scripts/Prepare-NativeOpenCodeGoCredentials.cjs" --out "$A"
  ;;
synthetic-repo)
  R="$A/inspect-repo"
  [ -e "$R" ] && { echo "$R already exists; not touching it" >&2; exit 1; }
  mkdir -p "$R/src" "$R/docs"
  cat >"$R/README.md" <<'EOF'
# demo-gateway
Synthetic repository for the Nexus A5.5 read-only inspection smoke test.
Authorization of model execution lives in src/auth.rs and is used by src/dispatch.rs.
EOF
  cat >"$R/src/auth.rs" <<'EOF'
//! Authorization gate for model execution.
use crate::dispatch::Grant;

/// Decide whether a model request may execute.
pub fn authorize_model_execution(prompt: &str, scope: &str) -> Option<Grant> {
    if scope != "model-only" {
        return None;
    }
    if prompt.is_empty() {
        return None;
    }
    Some(Grant { scope: scope.to_owned() })
}
EOF
  cat >"$R/src/dispatch.rs" <<'EOF'
use crate::auth::authorize_model_execution;

#[derive(Debug)]
pub struct Grant {
    pub scope: String,
}

pub fn run_model(prompt: &str) -> Option<Grant> {
    authorize_model_execution(prompt, "model-only")
}

pub fn replay(prompt: &str) -> Option<Grant> {
    authorize_model_execution(prompt, "model-only")
}
EOF
  cat >"$R/src/main.rs" <<'EOF'
mod auth;
mod dispatch;

fn main() {
    println!("{:?}", dispatch::run_model("hello"));
}
EOF
  echo "created $R (no credentials, no private content)"
  ;;
synthetic-code-repo)
  B="$A/code-base"; R="$B/repo"
  [ -e "$R" ] && { echo "$R already exists; not touching it" >&2; exit 1; }
  mkdir -p "$R/src" "$R/tests" "$B/worktrees"
  printf '[package]\nname = "calc"\nversion = "0.1.0"\nedition = "2021"\n\n[dependencies]\n' >"$R/Cargo.toml"
  printf '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "calc"\nversion = "0.1.0"\n' >"$R/Cargo.lock"
  printf 'target/\n' >"$R/.gitignore"
  printf 'pub fn add(a: i32, b: i32) -> i32 {\n    a - b\n}\n' >"$R/src/lib.rs"
  printf '#[test]\nfn adds_positive_numbers() {\n    assert_eq!(calc::add(2, 3), 5);\n}\n' >"$R/tests/add.rs"
  printf '# calc\nSynthetic crate for the Nexus A5.6 controlled-coding smoke test. `cargo test --offline` should pass.\n' >"$R/README.md"
  git -C "$R" init -q -b main
  git -C "$R" add -A
  git -C "$R" -c user.name=nexus-synthetic -c user.email=synthetic@invalid commit -qm "synthetic: failing add test"
  echo "created $R (synthetic; no credentials, no private content). Worktree root: $B/worktrees"
  ;;
check)
  # Read-only: is the running broker the installed build?
  rc=0; "$BIN/nexus-broker" identity --state-dir "$A/broker" || rc=$?
  case $rc in 0) ;; 3) echo "-> stop and start this instance before authorizing a live request" >&2;; 4) ;; esac
  exit $rc
  ;;
start)
  [ -d "$A/registry" ] || { echo "run prepare first" >&2; exit 2; }
  # Refuse to "start" over a live instance: a surviving old process silently
  # keeps serving (the A5.4 stale-broker incident) while the new one is refused.
  if "$BIN/nexus-broker" identity --state-dir "$A/broker" >/dev/null 2>&1 || [ $? -eq 3 ]; then
    echo "an instance is already running for $A:" >&2
    "$BIN/nexus-broker" identity --state-dir "$A/broker" >&2 || true
    echo "run 'stop' first (this script only ever stops processes whose command line names $A)" >&2
    exit 1
  fi
  UIDN=$(id -u)
  EXTRA_D=""; EXTRA_B=""
  if [ -n "${A55_WORKSPACE:-}" ]; then
    WID=${A55_WORKSPACE%%=*}; WPATH=${A55_WORKSPACE#*=}
    case "$WPATH" in /*) ;; *) echo "A55_WORKSPACE must be ID=ABSOLUTE_PATH" >&2; exit 2;; esac
    [ -d "$WPATH" ] || { echo "workspace path is not a directory" >&2; exit 2; }
    EXTRA_D="--workspace-bases $WPATH --enable-repo-inspect"
    EXTRA_B="--workspace $WID=$WPATH"
  fi
  if [ -n "${A56_CODE_SOURCE:-}" ]; then
    [ -z "${A55_WORKSPACE:-}" ] || { echo "use A55_WORKSPACE or A56_CODE_SOURCE, not both, for one instance" >&2; exit 2; }
    CID=${A56_CODE_SOURCE%%=*}; CPATH=${A56_CODE_SOURCE#*=}
    case "$CPATH" in /*) ;; *) echo "A56_CODE_SOURCE must be ID=ABSOLUTE_PATH" >&2; exit 2;; esac
    [ -d "$CPATH/.git" ] || { echo "the code source must be a git repository root" >&2; exit 2; }
    CBASE=$(dirname "$CPATH"); WTR="$CBASE/worktrees"
    mkdir -p "$WTR"
    DEPC=""
    if [ -n "${A61_DEP_CACHE:-}" ]; then
      case "$A61_DEP_CACHE" in /*) ;; *) echo "A61_DEP_CACHE must be an absolute directory" >&2; exit 2;; esac
      DEPC="--dep-cache $A61_DEP_CACHE"   # operator-populated offline crate cache (see docs/A6.1-SELFHOSTING-PROPOSAL.md)
    fi
    EXTRA_D="$DEPC --workspace-bases $CBASE --enable-repo-inspect --enable-repo-code --enable-writes --enable-process --require-human-approval --allow-nonindependent-approver-test-only --approver-cap $A/daemon/approver.cap --approver-uids $UIDN --worktree-root $WTR"
    EXTRA_B="--code-source $CID=$CPATH"
    # A6.1: pin the source to ONE exact commit (the daemon refuses any other HEAD) and, optionally,
    # limit the files the model may propose writes to (dir/ prefixes or exact files, comma separated).
    if [ -n "${A56_CODE_COMMIT:-}" ]; then
      case "$A56_CODE_COMMIT" in [0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f]*) ;; *) echo "A56_CODE_COMMIT must be a 40-hex commit id" >&2; exit 2;; esac
      [ ${#A56_CODE_COMMIT} -eq 40 ] || { echo "A56_CODE_COMMIT must be 40 hex characters" >&2; exit 2; }
      EXTRA_B="$EXTRA_B --code-commit $CID=$A56_CODE_COMMIT"
    fi
    if [ -n "${A61_CODE_WRITE_ALLOW:-}" ]; then
      EXTRA_B="$EXTRA_B --code-write-allow $CID=$A61_CODE_WRITE_ALLOW"
    fi
  fi
  # A6.1.3: multi-project mode. The operator registry (nexus project add/list/show/remove/repin)
  # replaces the single A56_CODE_SOURCE; the daemon makes working copies only for registered
  # projects, by id. Optional lower limits: A613_CAP_TURNS/TOOL_CALLS/EDITS/COMMANDS/MINUTES.
  if [ -n "${A613_PROJECT_REGISTRY:-}" ]; then
    [ -z "${A56_CODE_SOURCE:-}${A55_WORKSPACE:-}" ] || { echo "A613_PROJECT_REGISTRY replaces A56_CODE_SOURCE/A55_WORKSPACE; unset them" >&2; exit 2; }
    case "$A613_PROJECT_REGISTRY" in /*) ;; *) echo "A613_PROJECT_REGISTRY must be an absolute directory" >&2; exit 2;; esac
    [ -d "$A613_PROJECT_REGISTRY" ] || { echo "register at least one project first (nexus project add ...); registry directory missing" >&2; exit 2; }
    CBASE="$A/code-base"; WTR="$CBASE/worktrees"; mkdir -p "$WTR"
    DEPC=""
    if [ -n "${A61_DEP_CACHE:-}" ]; then
      case "$A61_DEP_CACHE" in /*) ;; *) echo "A61_DEP_CACHE must be an absolute directory" >&2; exit 2;; esac
      DEPC="--dep-cache $A61_DEP_CACHE"
    fi
    EXTRA_D="$DEPC --workspace-bases $CBASE --enable-repo-code --enable-writes --enable-process --require-human-approval --allow-nonindependent-approver-test-only --approver-cap $A/daemon/approver.cap --approver-uids $UIDN --worktree-root $WTR --project-registry $A613_PROJECT_REGISTRY"
    EXTRA_B="--project-registry $A613_PROJECT_REGISTRY"
    [ -z "${A613_CAP_TURNS:-}" ] || EXTRA_B="$EXTRA_B --code-cap-turns $A613_CAP_TURNS"
    [ -z "${A613_CAP_TOOL_CALLS:-}" ] || EXTRA_B="$EXTRA_B --code-cap-tool-calls $A613_CAP_TOOL_CALLS"
    [ -z "${A613_CAP_EDITS:-}" ] || EXTRA_B="$EXTRA_B --code-cap-edits $A613_CAP_EDITS"
    [ -z "${A613_CAP_COMMANDS:-}" ] || EXTRA_B="$EXTRA_B --code-cap-commands $A613_CAP_COMMANDS"
    [ -z "${A613_CAP_MINUTES:-}" ] || EXTRA_B="$EXTRA_B --code-cap-minutes $A613_CAP_MINUTES"
    [ -z "${A613_APPROVAL_TTL_SECS:-}" ] || EXTRA_B="$EXTRA_B --approval-ttl-secs $A613_APPROVAL_TTL_SECS"
  fi
  # shellcheck disable=SC2086
  "$BIN/nexusd" $EXTRA_D --db "$A/daemon/k.db" --socket "$A/daemon/n.sock" --cap "$A/daemon/issuer.cap" \
    --trust-mode shadow-test --witness "$A/daemon/k.wit.db" --allowed-uids "$UIDN" --enable-model-pilot \
    >"$A/daemon.log" 2>&1 &
  echo $! >"$A/daemon.pid"
  i=0; while [ ! -S "$A/daemon/n.sock" ] && [ $i -lt 100 ]; do sleep 0.1; i=$((i+1)); done
  [ -f "$A/credentials.json" ] || echo '{}' >"$A/credentials.json"
  chmod 600 "$A/credentials.json"
  "$BIN/nexus-broker" --state-dir "$A/broker" --socket "$A/broker.sock" --daemon-socket "$A/daemon/n.sock" \
    --cap "$A/daemon/issuer.cap" --credentials "$A/credentials.json" --repo-root "$REPO" \
    --registry-data-root "$A/registry" --transcript-dir "$A/transcripts" --allowed-uids "$UIDN" $EXTRA_B \
    >"$A/broker.log" 2>&1 &
  echo $! >"$A/broker.pid"
  sleep 1
  if ! "$BIN/nexus-broker" identity --state-dir "$A/broker"; then
    echo "broker did not come up as the installed build; see $A/broker.log" >&2
    exit 1
  fi
  echo "started (logs: $A/daemon.log, $A/broker.log)"
  ;;
stop)
  # Only processes of THIS instance: the pid must exist AND its command line
  # must name this instance's state paths. Unrelated processes are never signalled.
  stop_one() { # name, marker
    pf="$A/$1.pid"; [ -f "$pf" ] || return 0
    pid=$(cat "$pf" 2>/dev/null || true)
    if [ -n "$pid" ] && tr '\0' ' ' <"/proc/$pid/cmdline" 2>/dev/null | grep -qF -- "$2"; then
      kill "$pid" 2>/dev/null || true
    else
      echo "pid file for $1 does not match a process of this instance; not signalling" >&2
    fi
    rm -f "$pf"
  }
  stop_one broker "--state-dir $A/broker"
  stop_one daemon "--db $A/daemon/k.db"
  ;;
env)
  echo "export NEXUS_BROKER_SOCKET=$A/broker.sock"
  ;;
*) echo "usage: $0 prepare|credentials|start|synthetic-repo|synthetic-code-repo|check|stop|env" >&2; exit 2;;
esac
